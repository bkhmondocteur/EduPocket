// Fonction de traduction avec interpolation de variables : t('key', { name: 'Sami' })
window.t = function(key, params) {
    const lang = (window.EduPocketLang && window.EduPocketLang.current) || localStorage.getItem('edupocket_lang') || 'fr';
    const dict = window.EduPocketTranslations[lang] || window.EduPocketTranslations['fr'];
    let str = dict[key] || (window.EduPocketTranslations['fr'] && window.EduPocketTranslations['fr'][key]) || key;

    if (params && typeof params === 'object') {
        Object.keys(params).forEach(k => {
            str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]);
        });
    }
    return str;
};
